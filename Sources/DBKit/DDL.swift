import Foundation

// DDL shared by the dialects. Every statement is written out in full (one ALTER per change
// on Postgres) so the preview reads as a list of steps.

extension Dialect {
    func columnList(_ names: [String]) -> String {
        "(" + names.map(quoteIdentifier).joined(separator: ", ") + ")"
    }

    /// Index key parts: plain names are quoted; expressions and names the database already
    /// quoted are written as they are.
    func indexKeyList(_ parts: [String]) -> String {
        "(" + parts.map { p in
            p.hasPrefix("\"") || p.hasPrefix("`") || p.contains("(") ? p : quoteIdentifier(p)
        }.joined(separator: ", ") + ")"
    }

    /// The name a new index gets when the user leaves it empty.
    func defaultIndexName(table: String, columns: [String], unique: Bool) -> String {
        let base = ([table] + columns).joined(separator: "_") + (unique ? "_key" : "_idx")
        return String(base.prefix(63))
    }

    func foreignKeyClause(_ key: ForeignKeyInfo, from table: TableRef) -> String {
        var s = key.name.isEmpty ? "" : "CONSTRAINT \(quoteIdentifier(key.name)) "
        var target = key.referencedTable
        if target.schema == table.schema { target.schema = nil }
        s += "FOREIGN KEY \(columnList(key.columns)) REFERENCES \(qualified(target))"
        if !key.referencedColumns.allSatisfy(\.isEmpty) { s += " " + columnList(key.referencedColumns) }
        if key.onUpdate != "NO ACTION" { s += " ON UPDATE \(key.onUpdate)" }
        if key.onDelete != "NO ACTION" { s += " ON DELETE \(key.onDelete)" }
        return s
    }

    func commentLiteral(_ comment: String?) -> String {
        guard let comment, !comment.isEmpty else { return "NULL" }
        return literal(.text(comment))
    }

    /// The design's indexes, named.
    func namedIndexes(_ design: TableDesign) -> [IndexInfo] {
        design.indexes.map { d in
            var i = d.value
            if i.name.isEmpty { i.name = defaultIndexName(table: design.name, columns: i.columns, unique: i.isUnique) }
            return i
        }
    }
}

/// Whether `expression` is a constant SQL term that needs no parentheses as a default:
/// a number, a quoted string, NULL, TRUE/FALSE or one of the CURRENT_ keywords.
func isPlainDefault(_ expression: String) -> Bool {
    let e = expression.trimmingCharacters(in: .whitespaces)
    if e.isEmpty { return false }
    if Double(e) != nil { return true }
    if e.hasPrefix("'") && e.hasSuffix("'") && e.count >= 2 {
        // One string literal, not 'a' || 'b'.
        let inner = e.dropFirst().dropLast()
        return !inner.replacingOccurrences(of: "''", with: "").contains("'")
    }
    let upper = e.uppercased()
    return ["NULL", "TRUE", "FALSE", "CURRENT_TIMESTAMP", "CURRENT_DATE", "CURRENT_TIME"].contains(upper)
}

// MARK: - PostgreSQL

extension PostgresDialect {
    public var commonTypes: [String] {
        ["bigint", "bigserial", "boolean", "bytea", "char", "date", "double precision", "inet", "integer",
         "interval", "json", "jsonb", "numeric", "real", "serial", "smallint", "text", "time",
         "timestamp", "timestamptz", "uuid", "varchar"]
    }

    func columnDefinition(_ c: ColumnInfo) -> String {
        var s = "\(quoteIdentifier(c.name)) \(c.typeName)"
        if c.isAutoIncrement {
            s += " GENERATED BY DEFAULT AS IDENTITY"
        } else if let g = c.generated {
            s += " " + g
        }
        if !c.isNullable { s += " NOT NULL" }
        if let d = c.defaultExpression, !c.isAutoIncrement, c.generated == nil { s += " DEFAULT \(d)" }
        return s
    }

    public func alterTable(_ c: StructureChange) throws -> DDLPlan {
        let table = c.original.table
        let t = qualified(table)
        var s: [String] = []
        for key in c.droppedForeignKeys {
            s.append("ALTER TABLE \(t) DROP CONSTRAINT \(quoteIdentifier(key.name))")
        }
        if c.primaryKeyChanged, !c.oldPrimaryKey.isEmpty {
            let name = c.original.primaryIndex?.name ?? "\(table.name)_pkey"
            s.append("ALTER TABLE \(t) DROP CONSTRAINT \(quoteIdentifier(name))")
        }
        for index in c.droppedIndexes {
            s.append(index.isConstraint
                ? "ALTER TABLE \(t) DROP CONSTRAINT \(quoteIdentifier(index.name))"
                : "DROP INDEX \(qualified(TableRef(schema: table.schema, index.name)))")
        }
        for column in c.droppedColumns {
            s.append("ALTER TABLE \(t) DROP COLUMN \(quoteIdentifier(column.name))")
        }
        for a in c.alteredColumns where a.renamed {
            s.append("ALTER TABLE \(t) RENAME COLUMN \(quoteIdentifier(a.old.name)) TO \(quoteIdentifier(a.new.name))")
        }
        for a in c.alteredColumns where a.definitionChanged {
            let alter = "ALTER TABLE \(t) ALTER COLUMN \(quoteIdentifier(a.new.name))"
            // The old default goes first: it may not convert to the new type.
            if a.defaultChanged, a.old.defaultExpression != nil { s.append("\(alter) DROP DEFAULT") }
            if a.typeChanged { s.append("\(alter) TYPE \(a.new.typeName)") }
            if a.nullabilityChanged { s.append("\(alter) \(a.new.isNullable ? "DROP" : "SET") NOT NULL") }
            if a.autoIncrementChanged {
                s.append(a.new.isAutoIncrement ? "\(alter) ADD GENERATED BY DEFAULT AS IDENTITY" : "\(alter) DROP IDENTITY")
            }
            if a.defaultChanged, let d = a.new.defaultExpression { s.append("\(alter) SET DEFAULT \(d)") }
            if a.commentChanged {
                s.append("COMMENT ON COLUMN \(t).\(quoteIdentifier(a.new.name)) IS \(commentLiteral(a.new.comment))")
            }
        }
        for column in c.addedColumns {
            s.append("ALTER TABLE \(t) ADD COLUMN \(columnDefinition(column))")
            if let comment = column.comment, !comment.isEmpty {
                s.append("COMMENT ON COLUMN \(t).\(quoteIdentifier(column.name)) IS \(commentLiteral(comment))")
            }
        }
        if c.primaryKeyChanged, !c.newPrimaryKey.isEmpty {
            s.append("ALTER TABLE \(t) ADD PRIMARY KEY \(columnList(c.newPrimaryKey))")
        }
        for index in c.createdIndexes {
            s.append(createIndex(index, on: table, tableName: c.original.table.name))
        }
        for key in c.addedForeignKeys {
            s.append("ALTER TABLE \(t) ADD \(foreignKeyClause(key, from: table))")
        }
        if c.commentChanged {
            s.append("COMMENT ON TABLE \(t) IS \(commentLiteral(c.design.comment))")
        }
        if let name = c.renamedTable {
            s.append("ALTER TABLE \(t) RENAME TO \(quoteIdentifier(name))")
        }
        return DDLPlan(statements: s)
    }

    func createIndex(_ index: IndexInfo, on table: TableRef, tableName: String) -> String {
        let name = index.name.isEmpty
            ? defaultIndexName(table: tableName, columns: index.columns, unique: index.isUnique) : index.name
        var s = "CREATE \(index.isUnique ? "UNIQUE " : "")INDEX \(quoteIdentifier(name)) ON \(qualified(table))"
        if let m = index.method, !m.isEmpty, m.lowercased() != "btree" { s += " USING \(m)" }
        s += " " + indexKeyList(index.columns)
        if let p = index.predicate, !p.isEmpty { s += " WHERE \(p)" }
        return s
    }

    public func createTable(_ design: TableDesign, schema: String?) -> DDLPlan {
        let table = TableRef(schema: schema, design.name)
        let t = qualified(table)
        var parts = design.columns.map { columnDefinition($0.value) }
        if !design.primaryKey.isEmpty { parts.append("PRIMARY KEY \(columnList(design.primaryKey))") }
        parts += design.foreignKeys.map { foreignKeyClause($0.value, from: table) }
        var s = ["CREATE TABLE \(t) (\n  " + parts.joined(separator: ",\n  ") + "\n)"]
        s += namedIndexes(design).map { createIndex($0, on: table, tableName: design.name) }
        for c in design.columns {
            if let comment = c.value.comment, !comment.isEmpty {
                s.append("COMMENT ON COLUMN \(t).\(quoteIdentifier(c.value.name)) IS \(commentLiteral(comment))")
            }
        }
        if !design.comment.isEmpty { s.append("COMMENT ON TABLE \(t) IS \(commentLiteral(design.comment))") }
        return DDLPlan(statements: s)
    }

    public func drop(_ object: DatabaseObject, options: DropOptions) throws -> DDLPlan {
        let what = switch object.kind {
        case .table: "TABLE"
        case .view: "VIEW"
        case .materializedView: "MATERIALIZED VIEW"
        case .sequence: "SEQUENCE"
        case .function: "FUNCTION"
        case .procedure: "PROCEDURE"
        }
        return DDLPlan(statements: ["DROP \(what) \(routineName(object))\(options.cascade ? " CASCADE" : "")"])
    }

    /// A routine with its argument types, so one overload is meant; any other object's name.
    func routineName(_ object: DatabaseObject) -> String {
        guard object.kind.isRoutine, let signature = object.signature else { return qualified(object.ref) }
        return "\(qualified(object.ref))(\(signature))"
    }

    public func supportsDefinitions(of kind: DefinitionKind) -> Bool { true }

    /// Views and routines keep their privileges and dependents through `CREATE OR REPLACE`;
    /// materialized views and triggers have none (before 14 for triggers), and the drop runs in
    /// the commit's transaction, so a failure changes nothing.
    public func replaceMethod(for kind: DefinitionKind) -> ReplaceMethod {
        switch kind {
        case .view, .function, .procedure: .orReplace
        case .materializedView, .trigger: .dropFirst
        }
    }

    public func dropStatement(_ object: DefinedObject) throws -> String {
        if object.kind == .trigger {
            guard let table = object.table else { throw DatabaseError("The trigger's table isn't known.") }
            return "DROP TRIGGER \(quoteIdentifier(object.ref.name)) ON \(qualified(table))"
        }
        return try drop(object.object!, options: DropOptions()).statements[0]
    }

    /// `LIKE … INCLUDING ALL` copies columns, defaults, identity, generated columns, constraints
    /// (but not foreign keys), indexes, comments and storage. Rows are copied with the identity
    /// values they have, and identity sequences moved past them.
    public func clone(_ structure: TableStructure, as name: String, withData: Bool) throws -> DDLPlan {
        let source = qualified(structure.table)
        let target = qualified(TableRef(schema: structure.table.schema, name))
        var s = ["CREATE TABLE \(target) (LIKE \(source) INCLUDING ALL)"]
        if withData {
            let copied = structure.columns.filter { !($0.generated?.hasPrefix("GENERATED ALWAYS AS (") ?? false) }.map(\.name)
            let always = structure.columns.contains { $0.generated == "GENERATED ALWAYS AS IDENTITY" }
            s.append("INSERT INTO \(target) \(columnList(copied))\(always ? " OVERRIDING SYSTEM VALUE" : "")"
                     + " SELECT \(copied.map(quoteIdentifier).joined(separator: ", ")) FROM \(source)")
            for c in structure.columns where c.generated?.hasSuffix("AS IDENTITY") == true {
                s.append("SELECT setval(pg_get_serial_sequence(\(literal(.text(target))), \(literal(.text(c.name)))),"
                         + " max(\(quoteIdentifier(c.name)))) FROM \(target)")
            }
        }
        return DDLPlan(statements: s, notes: ["Foreign keys and triggers aren't copied."])
    }

    public func truncate(_ table: TableRef, options: TruncateOptions, hasAutoIncrement: Bool) -> DDLPlan {
        var s = "TRUNCATE TABLE \(qualified(table))"
        if options.restartIdentity { s += " RESTART IDENTITY" }
        if options.cascade { s += " CASCADE" }
        return DDLPlan(statements: [s])
    }

    public func rename(_ object: DatabaseObject, to name: String) throws -> DDLPlan {
        let what = switch object.kind {
        case .table: "TABLE"
        case .view: "VIEW"
        case .materializedView: "MATERIALIZED VIEW"
        case .sequence: "SEQUENCE"
        case .function, .procedure:
            throw DatabaseError("To rename a \(object.kind.rawValue), change its name in its definition.")
        }
        return DDLPlan(statements: ["ALTER \(what) \(qualified(object.ref)) RENAME TO \(quoteIdentifier(name))"])
    }
}

// MARK: - MySQL / MariaDB

extension MySQLDialect {
    public var commonTypes: [String] {
        ["bigint", "binary", "bit", "blob", "boolean", "char", "date", "datetime", "decimal", "double",
         "enum", "float", "int", "json", "longblob", "longtext", "mediumint", "mediumtext", "set",
         "smallint", "text", "time", "timestamp", "tinyint", "varbinary", "varchar(255)", "year"]
    }

    /// Everything MySQL needs to (re)define a column: a MODIFY that leaves out the collation,
    /// AUTO_INCREMENT or ON UPDATE silently drops them.
    func columnDefinition(_ c: ColumnInfo) -> String {
        var s = "\(quoteIdentifier(c.name)) \(c.typeName)"
        if let collation = c.collation, Self.takesCollation(c.typeName) { s += " COLLATE \(collation)" }
        if let g = c.generated {
            s += " " + g
            s += c.isNullable ? "" : " NOT NULL"
        } else {
            s += c.isNullable ? " NULL" : " NOT NULL"
            if let d = c.defaultExpression { s += " DEFAULT \(d)" }
            if let u = c.onUpdate { s += " ON UPDATE \(u)" }
            if c.isAutoIncrement { s += " AUTO_INCREMENT" }
        }
        if let comment = c.comment, !comment.isEmpty { s += " COMMENT \(literal(.text(comment)))" }
        return s
    }

    static func takesCollation(_ type: String) -> Bool {
        let base = type.lowercased().prefix { $0.isLetter }
        return ["char", "varchar", "tinytext", "text", "mediumtext", "longtext", "enum", "set"].contains(String(base))
    }

    func indexClause(_ index: IndexInfo, tableName: String) -> String {
        let name = index.name.isEmpty
            ? defaultIndexName(table: tableName, columns: index.columns, unique: index.isUnique) : index.name
        let method = index.method?.uppercased() ?? ""
        let kind = method == "FULLTEXT" ? "FULLTEXT " : method == "SPATIAL" ? "SPATIAL " : index.isUnique ? "UNIQUE " : ""
        var s = "\(kind)INDEX \(quoteIdentifier(name)) \(indexKeyList(index.columns))"
        // BTREE is InnoDB's default; HASH matters for MEMORY tables.
        if method == "HASH" { s += " USING HASH" }
        return s
    }

    public func alterTable(_ c: StructureChange) throws -> DDLPlan {
        let table = c.original.table
        let t = qualified(table)
        var statements: [String] = []
        // Dropping and adding a foreign key of the same name can't share one ALTER.
        if !c.droppedForeignKeys.isEmpty {
            statements.append("ALTER TABLE \(t) " + c.droppedForeignKeys.map {
                "DROP FOREIGN KEY \(quoteIdentifier($0.name))"
            }.joined(separator: ", "))
        }
        var parts: [String] = []
        if c.primaryKeyChanged, !c.oldPrimaryKey.isEmpty { parts.append("DROP PRIMARY KEY") }
        parts += c.droppedIndexes.map { "DROP INDEX \(quoteIdentifier($0.name))" }
        parts += c.droppedColumns.map { "DROP COLUMN \(quoteIdentifier($0.name))" }
        for a in c.alteredColumns {
            if !a.definitionChanged {
                parts.append("RENAME COLUMN \(quoteIdentifier(a.old.name)) TO \(quoteIdentifier(a.new.name))")
            } else if a.renamed {
                parts.append("CHANGE COLUMN \(quoteIdentifier(a.old.name)) \(columnDefinition(a.new))")
            } else {
                parts.append("MODIFY COLUMN \(columnDefinition(a.new))")
            }
        }
        // New columns go where they are in the design; MySQL keeps column order.
        let names = c.design.columns.map(\.value.name)
        for d in c.design.columns where d.origin == nil {
            var clause = "ADD COLUMN \(columnDefinition(d.value))"
            if let i = names.firstIndex(of: d.value.name), i < names.count - 1 {
                clause += i == 0 ? " FIRST" : " AFTER \(quoteIdentifier(names[i - 1]))"
            }
            parts.append(clause)
        }
        if c.primaryKeyChanged, !c.newPrimaryKey.isEmpty { parts.append("ADD PRIMARY KEY \(columnList(c.newPrimaryKey))") }
        parts += c.createdIndexes.map { "ADD " + indexClause($0, tableName: table.name) }
        parts += c.addedForeignKeys.map { "ADD " + foreignKeyClause($0, from: table) }
        if c.commentChanged { parts.append("COMMENT = \(literal(.text(c.design.comment)))") }
        if let name = c.renamedTable { parts.append("RENAME TO \(quoteIdentifier(name))") }
        if !parts.isEmpty { statements.append("ALTER TABLE \(t)\n  " + parts.joined(separator: ",\n  ")) }
        return DDLPlan(statements: statements, isAtomic: statements.count <= 1)
    }

    public func createTable(_ design: TableDesign, schema: String?) -> DDLPlan {
        let table = TableRef(schema: schema, design.name)
        var parts = design.columns.map { columnDefinition($0.value) }
        if !design.primaryKey.isEmpty { parts.append("PRIMARY KEY \(columnList(design.primaryKey))") }
        parts += namedIndexes(design).map { indexClause($0, tableName: design.name) }
        parts += design.foreignKeys.map { foreignKeyClause($0.value, from: table) }
        var s = "CREATE TABLE \(qualified(table)) (\n  " + parts.joined(separator: ",\n  ") + "\n)"
        if !design.comment.isEmpty { s += " COMMENT = \(literal(.text(design.comment)))" }
        return DDLPlan(statements: [s])
    }

    func foreignKeyChecks(_ off: Bool) -> DDLPlan {
        off ? DDLPlan(setup: ["SET FOREIGN_KEY_CHECKS = 0"], teardown: ["SET FOREIGN_KEY_CHECKS = 1"]) : DDLPlan()
    }

    public func drop(_ object: DatabaseObject, options: DropOptions) throws -> DDLPlan {
        let what = switch object.kind {
        case .table: "TABLE"
        case .view: "VIEW"
        case .function: "FUNCTION"
        case .procedure: "PROCEDURE"
        case .materializedView, .sequence: throw DatabaseError("MySQL has no \(object.kind.rawValue)s.")
        }
        var plan = DDLPlan(statements: ["DROP \(what) \(qualified(object.ref))"])
        if object.kind == .table { plan = foreignKeyChecks(options.ignoreForeignKeys) + plan }
        return plan
    }

    public func supportsDefinitions(of kind: DefinitionKind) -> Bool { kind != .materializedView }

    /// Views take `CREATE OR REPLACE`. MySQL has no such thing for routines (MariaDB does), so
    /// they're checked under a scratch name first; triggers are dropped and created again.
    public func replaceMethod(for kind: DefinitionKind) -> ReplaceMethod {
        switch kind {
        case .view, .materializedView: .orReplace
        case .function, .procedure: .checkThenDrop
        case .trigger: .dropFirst
        }
    }

    public func dropStatement(_ object: DefinedObject) throws -> String {
        if object.kind == .trigger { return "DROP TRIGGER \(qualified(object.ref))" }
        return try drop(object.object!, options: DropOptions()).statements[0]
    }

    /// `CREATE TABLE … LIKE` copies columns, indexes and AUTO_INCREMENT, not foreign keys.
    public func clone(_ structure: TableStructure, as name: String, withData: Bool) throws -> DDLPlan {
        let source = qualified(structure.table)
        let target = qualified(TableRef(schema: structure.table.schema, name))
        var s = ["CREATE TABLE \(target) LIKE \(source)"]
        if withData {
            let copied = structure.columns.filter { $0.generated == nil }.map(\.name)
            s.append("INSERT INTO \(target) \(columnList(copied)) SELECT \(copied.map(quoteIdentifier).joined(separator: ", ")) FROM \(source)")
        }
        return DDLPlan(statements: s, isAtomic: false, notes: ["Foreign keys and triggers aren't copied."])
    }

    public func truncate(_ table: TableRef, options: TruncateOptions, hasAutoIncrement: Bool) -> DDLPlan {
        foreignKeyChecks(options.ignoreForeignKeys) + DDLPlan(statements: ["TRUNCATE TABLE \(qualified(table))"])
    }

    public func rename(_ object: DatabaseObject, to name: String) throws -> DDLPlan {
        guard object.kind == .table || object.kind == .view else {
            throw DatabaseError("Only tables and views can be renamed from here.")
        }
        let target = TableRef(schema: object.ref.schema, name)
        return DDLPlan(statements: ["RENAME TABLE \(qualified(object.ref)) TO \(qualified(target))"])
    }
}
