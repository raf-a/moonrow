import DBKit
import Foundation
import Testing
@testable import AppCore

@Suite struct StructureEditorTests {
    let structure = TableStructure(
        table: TableRef("orders"),
        columns: [
            ColumnInfo(name: "id", typeName: "integer", isNullable: false, primaryKeyPosition: 1),
            ColumnInfo(name: "customer", typeName: "integer"),
            ColumnInfo(name: "placed", typeName: "date"),
        ],
        indexes: [
            IndexInfo(name: "orders_pkey", columns: ["id"], isUnique: true, isPrimary: true),
            IndexInfo(name: "orders_customer_placed", columns: ["customer", "placed"]),
        ],
        foreignKeys: [ForeignKeyInfo(name: "orders_customer_fk", columns: ["customer"], referencedTable: TableRef("customers"), referencedColumns: ["id"])])

    @Test func renameFollowsIntoKeysAndIndexes() {
        var e = StructureEditor(structure)
        e.setColumn(1) { $0.name = "customer_id" }
        #expect(e.indexes[0].value.columns == ["customer_id", "placed"])
        #expect(e.foreignKeys[0].value.columns == ["customer_id"])
        #expect(e.changedFields(ofColumn: 1) == [.name])
        #expect(e.changedFields(ofIndex: 0).isEmpty)
        let c = e.change
        #expect(c.alteredColumns.count == 1 && c.droppedIndexes.isEmpty && c.droppedForeignKeys.isEmpty)
    }

    @Test func deletingAColumnTakesItsIndexColumnAndKey() {
        var e = StructureEditor(structure)
        e.deleteColumns([1])
        #expect(e.columns[1].isDeleted)
        #expect(e.indexes[0].value.columns == ["placed"])
        #expect(e.foreignKeys[0].isDeleted)
        e.deleteColumns([2])
        #expect(e.indexes[0].isDeleted)
        #expect(e.design.columns.map(\.value.name) == ["id"])
        // New rows simply go away.
        let row = e.addColumn(type: "text")
        e.deleteColumns([row])
        #expect(e.columns.count == 3)
    }

    @Test func newColumnsGetFreeNames() {
        var e = StructureEditor(structure)
        let a = e.addColumn(type: "text")
        let b = e.addColumn(type: "text")
        #expect(e.columns[a].value.name == "column" && e.columns[b].value.name == "column_2")
        let copy = e.duplicateColumn(0)
        #expect(e.columns[copy].value.name == "column_3" && e.columns[copy].value.typeName == "integer")
        #expect(copy == 1)
    }

    @Test func primaryKeyColumnsBecomeNotNull() {
        var e = StructureEditor(structure)
        e.togglePrimaryKey(2)
        #expect(e.primaryKey == ["id", "placed"])
        #expect(e.columns[2].value.isNullable == false)
        #expect(e.primaryKeyChanged)
        e.togglePrimaryKey(2)
        #expect(!e.primaryKeyChanged)
    }

    @Test func problemsBlockThePlan() {
        var e = StructureEditor(structure)
        e.setColumn(1) { $0.name = "ID" }
        #expect(e.problem(for: PostgresDialect()) == "There are two columns named ID.")
        #expect(throws: DatabaseError.self) { try e.plan(for: PostgresDialect()) }
        e.setColumn(1) { $0.name = "customer"; $0.typeName = "" }
        #expect(e.problem(for: PostgresDialect()) == "Column customer needs a type.")
        #expect(e.problem(for: SQLiteDialect()) == nil)
    }

    @Test func newTablePlan() throws {
        var e = StructureEditor.newTable(TableRef(schema: "app", "tags"), dialect: PostgresDialect())
        #expect(e.hasChanges)
        e.addColumn(type: "text")
        #expect(try e.plan(for: PostgresDialect()).statements == ["""
            CREATE TABLE "app"."tags" (
              "id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
              "column" text,
              PRIMARY KEY ("id")
            )
            """])
    }

    @Test func defaultInput() {
        let pg = PostgresDialect()
        #expect(DefaultInput.sql(from: "", dialect: pg) == nil)
        #expect(DefaultInput.sql(from: " 42 ", dialect: pg) == "42")
        #expect(DefaultInput.sql(from: "pending", dialect: pg) == "'pending'")
        #expect(DefaultInput.sql(from: "it's", dialect: pg) == "'it''s'")
        #expect(DefaultInput.sql(from: "'x'", dialect: pg) == "'x'")
        #expect(DefaultInput.sql(from: "now()", dialect: pg) == "now()")
        #expect(DefaultInput.sql(from: "gen_random_uuid()", dialect: pg) == "gen_random_uuid()")
        #expect(DefaultInput.sql(from: "current_timestamp", dialect: pg) == "current_timestamp")
        #expect(DefaultInput.sql(from: "'{}'::jsonb", dialect: pg) == "'{}'::jsonb")
        #expect(DefaultInput.sql(from: "hello (world)", dialect: pg) == "'hello (world)'")
    }
}
