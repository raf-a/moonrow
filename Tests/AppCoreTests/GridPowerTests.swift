@Suite struct PasteRangeTests {
    private func cells(_ a: [GridPaste.Assignment]) -> [String] {
        a.map { "\($0.row),\($0.column)=\($0.text)" }
    }

    @Test func readsTabSeparatedLines() {
        #expect(GridPaste.fields("a\tb\nc\td\n") == [["a", "b"], ["c", "d"]])
        #expect(GridPaste.fields("a\tb\r\nc\t\r\n") == [["a", "b"], ["c", ""]])
        #expect(GridPaste.fields("one") == [["one"]])
        #expect(GridPaste.fields("\t") == [["", ""]])
        #expect(GridPaste.fields("").isEmpty)
        #expect(GridPaste.fields("\n") .isEmpty)
        // Only one trailing line break is dropped: a blank last line is a row.
        #expect(GridPaste.fields("a\n\n") == [["a"], [""]])
    }

    @Test func singleValueFillsEverySelectedCell() {
        let a = GridPaste.assignments([["x"]], rows: [1, 3], columns: 0...1, rowCount: 5, columnCount: 3)
        #expect(cells(a) == ["1,0=x", "1,1=x", "3,0=x", "3,1=x"])
    }

    @Test func oneRowRepeatsDownSelectedRows() {
        let a = GridPaste.assignments([["a", "b"]], rows: [0, 2], columns: 1...1, rowCount: 5, columnCount: 3)
        #expect(cells(a) == ["0,1=a", "0,2=b", "2,1=a", "2,2=b"])
    }

    @Test func oneColumnRepeatsAcrossSelectedColumns() {
        let a = GridPaste.assignments([["a"], ["b"]], rows: [3], columns: 0...1, rowCount: 5, columnCount: 3)
        #expect(cells(a) == ["3,0=a", "4,0=b", "3,1=a", "4,1=b"])
    }

    @Test func blockPastesOnceFromTopLeftAndStopsAtTheEdges() {
        let block = [["a", "b", "c"], ["d", "e", "f"], ["g", "h", "i"]]
        let a = GridPaste.assignments(block, rows: [3, 4], columns: 1...1, rowCount: 5, columnCount: 3)
        #expect(cells(a) == ["3,1=a", "3,2=b", "4,1=d", "4,2=e"])
        // Short lines leave the rest of the block empty.
        let ragged = GridPaste.assignments([["a", "b"], ["c"]], rows: [0], columns: 0...0, rowCount: 5, columnCount: 3)
        #expect(cells(ragged) == ["0,0=a", "0,1=b", "1,0=c", "1,1="])
    }

    @Test func nothingSelectedOrNothingToPaste() {
        #expect(GridPaste.assignments([["a"]], rows: [], columns: 0...0, rowCount: 5, columnCount: 3).isEmpty)
        #expect(GridPaste.assignments([], rows: [1], columns: 0...0, rowCount: 5, columnCount: 3).isEmpty)
    }

    @Test func valuesFollowTheColumn() {
        let int = ColumnInfo(name: "n", typeName: "integer", isNullable: true)
        let text = ColumnInfo(name: "t", typeName: "text", isNullable: false)
        #expect(GridPaste.value("42", column: int) == .integer(42))
        #expect(GridPaste.value("4x", column: int) == .text("4x"))
        // An empty field is NULL where allowed (⌘C writes NULL as empty), else ''.
        #expect(GridPaste.value("", column: int) == .null)
        #expect(GridPaste.value("", column: text) == .text(""))
        var generated = int
        generated.generated = "GENERATED ALWAYS AS (n + 1) STORED"
        #expect(!GridPaste.accepts(generated))
        generated.generated = "GENERATED BY DEFAULT AS IDENTITY"
        #expect(GridPaste.accepts(generated))
        #expect(GridPaste.accepts(int))
    }
}

@Suite struct ColumnVisibilityTests {
    let columns = ["id", "name", "email", "age"]

    @Test func defaultShowsTheTableOrder() {
        let layout = ColumnLayout()
        #expect(layout.visible(columns) == [0, 1, 2, 3])
        #expect(layout.isDefault)
    }

    @Test func hidingAndShowing() {
        var layout = ColumnLayout()
        let hid = layout.setHidden(true, "email", columns: columns)
        #expect(hid)
        #expect(layout.visible(columns) == [0, 1, 3])
        #expect(layout.arranged(columns) == [0, 1, 2, 3])
        layout.setHidden(false, "email", columns: columns)
        #expect(layout.isDefault)
    }

    @Test func theLastShownColumnStays() {
        var layout = ColumnLayout()
        for c in ["id", "name", "email"] { layout.setHidden(true, c, columns: columns) }
        let last = layout.setHidden(true, "age", columns: columns)
        #expect(!last)
        #expect(layout.visible(columns) == [3])
        // A layout that hides everything (the table changed) shows everything.
        let all = ColumnLayout(order: [], hidden: ["x"])
        #expect(ColumnLayout(order: [], hidden: ["id"]).visible(["id"]) == [0])
        #expect(all.visible(columns) == [0, 1, 2, 3])
    }

    @Test func reordering() {
        var layout = ColumnLayout()
        layout.move(from: 3, to: 0, columns: columns)
        #expect(layout.visible(columns) == [3, 0, 1, 2])
        layout.move(from: 0, to: 3, columns: columns)
        #expect(layout.isDefault)
    }

    @Test func dragOrderKeepsHiddenColumnsInPlace() {
        var layout = ColumnLayout()
        layout.setHidden(true, "name", columns: columns)
        // The grid shows id, email, age; age is dragged first.
        layout.setShownOrder(["age", "id", "email"], columns: columns)
        #expect(layout.arranged(columns).map { columns[$0] } == ["age", "name", "id", "email"])
        #expect(layout.visible(columns).map { columns[$0] } == ["age", "id", "email"])
    }

    @Test func survivesColumnChanges() {
        let layout = ColumnLayout(order: ["age", "gone", "id", "name", "email"], hidden: ["gone", "name"])
        // "gone" was dropped; "phone" was added after "email".
        let now = ["id", "name", "email", "phone", "age"]
        #expect(layout.visible(now).map { now[$0] } == ["age", "id", "email", "phone"])
        // A new first column goes first.
        #expect(layout.visible(["key"] + columns).first == 0)
    }

    @MainActor @Test func storedPerTable() throws {
        let dir = FileManager.default.temporaryDirectory.appending(path: UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: dir) }
        let url = ColumnLayouts.fileURL(root: dir, connection: UUID())
        let store = ColumnLayouts(fileURL: url)
        let users = TableRef(schema: "public", "users")
        var layout = ColumnLayout()
        layout.setHidden(true, "email", columns: columns)
        store.set(layout, for: users)
        #expect(ColumnLayouts(fileURL: url).layout(for: users) == layout)
        #expect(ColumnLayouts(fileURL: url).layout(for: TableRef(schema: "other", "users")).isDefault)
        store.rename(users, to: TableRef(schema: "public", "people"))
        let reread = ColumnLayouts(fileURL: url)
        #expect(reread.layout(for: users).isDefault)
        #expect(reread.layout(for: TableRef(schema: "public", "people")) == layout)
        // A broken file reads as no layouts.
        try Data("{".utf8).write(to: url)
        #expect(ColumnLayouts(fileURL: url).layout(for: users).isDefault)
    }
}

@Suite struct CellViewerTests {
    @Test func prettyJSONKeepsKeyOrderAndValues() {
        let json = #"{"b":1,"a":[1, 2.50,{"x":"a,b:{c}\"q\""}],"e":{},"f":[] ,"n":null}"#
        #expect(CellViewer.prettyJSON(json) == #"""
            {
              "b": 1,
              "a": [
                1,
                2.50,
                {
                  "x": "a,b:{c}\"q\""
                }
              ],
              "e": {},
              "f": [],
              "n": null
            }
            """#)
        #expect(CellViewer.prettyJSON("[]") == "[]")
        #expect(CellViewer.prettyJSON("42") == nil)
        #expect(CellViewer.prettyJSON("{nope}") == nil)
        #expect(CellViewer.prettyJSON("plain text") == nil)
    }

    @Test func hexDump() {
        let data = Data("Hello, world!\n\u{0}\u{1}ABC".utf8)
        #expect(CellViewer.hexDump(data) == """
            00000000  48 65 6c 6c 6f 2c 20 77  6f 72 6c 64 21 0a 00 01  |Hello, world!...|
            00000010  41 42 43                                          |ABC|
            """)
        #expect(CellViewer.hexDump(Data(count: 40), limit: 16).hasSuffix("… 24 more bytes"))
    }

    @Test func filesLoadByColumnType() {
        #expect(CellViewer.value(fromFile: Data([0xFF]), typeName: "bytea") == .blob(Data([0xFF])))
        #expect(CellViewer.value(fromFile: Data("hi".utf8), typeName: "LONGBLOB") == .blob(Data("hi".utf8)))
        #expect(CellViewer.value(fromFile: Data("hi".utf8), typeName: "text") == .text("hi"))
        #expect(CellViewer.value(fromFile: Data([0xFF, 0xFE, 0x00]), typeName: "text") == nil)
    }
}

@Suite struct QuickFilterTests {
    private func titles(_ v: DBValue?) -> [String] {
        QuickFilter.conditions(column: "c", value: v).map(QuickFilter.title)
    }

    @Test func conditionsFollowTheValue() {
        #expect(titles(.integer(42)) == ["c = 42", "c ≠ 42", "c < 42", "c > 42", "c IS NULL", "c IS NOT NULL"])
        #expect(titles(.text("Alice")) == ["c = 'Alice'", "c ≠ 'Alice'", "c contains 'Alice'", "c IS NULL", "c IS NOT NULL"])
        #expect(titles(.text("2026-10-12 09:00")) == ["c = '2026-10-12 09:00'", "c ≠ '2026-10-12 09:00'",
                                                       "c < '2026-10-12 09:00'", "c > '2026-10-12 09:00'", "c IS NULL", "c IS NOT NULL"])
        #expect(titles(.null) == ["c IS NULL", "c IS NOT NULL"])
        #expect(titles(nil) == ["c IS NULL", "c IS NOT NULL"])
        #expect(titles(.blob(Data([1]))) == ["c IS NULL", "c IS NOT NULL"])
        #expect(titles(.text("")) == ["c = ''", "c ≠ ''", "c IS NULL", "c IS NOT NULL"])
        #expect(titles(.text(String(repeating: "x", count: 50))).first == "c = '\(String(repeating: "x", count: 40))…'")
        // The condition carries the whole value.
        #expect(QuickFilter.conditions(column: "c", value: .bool(true)).first == FilterCondition(.column("c"), .equal, "true"))
    }
}
