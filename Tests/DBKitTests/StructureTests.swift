@testable import DBKit

private let sqlite = SQLiteDialect()
private let pg = PostgresDialect()
private let my = MySQLDialect()

/// `users (id PK, email NOT NULL, name, age DEFAULT 0)` with an index on email and a key to teams.
private func users(schema: String? = nil, definition: String? = nil) -> TableStructure {
    TableStructure(
        table: TableRef(schema: schema, "users"),
        columns: [
            ColumnInfo(name: "id", typeName: "integer", isNullable: false, primaryKeyPosition: 1),
            ColumnInfo(name: "email", typeName: "varchar(100)", isNullable: false),
            ColumnInfo(name: "name", typeName: "text"),
            ColumnInfo(name: "age", typeName: "integer", defaultExpression: "0"),
            ColumnInfo(name: "team_id", typeName: "integer"),
        ],
        indexes: [
            IndexInfo(name: "users_pkey", columns: ["id"], isUnique: true, isPrimary: true),
            IndexInfo(name: "users_email_idx", columns: ["email"], definition: "CREATE INDEX users_email_idx ON users (email)"),
        ],
        foreignKeys: [ForeignKeyInfo(name: "users_team_fk", columns: ["team_id"], referencedTable: TableRef(schema: schema, "teams"), referencedColumns: ["id"], onDelete: "CASCADE")],
        definition: definition)
}

private func column(_ d: inout TableDesign, _ name: String, _ edit: (inout ColumnInfo) -> Void) {
    let i = d.columns.firstIndex { $0.value.name == name }!
    edit(&d.columns[i].value)
}

@Suite struct StructureChangeTests {
    @Test func unchangedDesignIsEmpty() {
        let s = users()
        #expect(StructureChange(from: s, to: TableDesign(s)).isEmpty)
    }

    @Test func renamingAColumnLeavesItsIndexAndKeyAlone() {
        let s = users()
        var d = TableDesign(s)
        column(&d, "email") { $0.name = "mail" }
        column(&d, "team_id") { $0.name = "team" }
        // The editor follows renames into indexes and keys.
        d.indexes[0].value.columns = ["mail"]
        d.foreignKeys[0].value.columns = ["team"]
        let c = StructureChange(from: s, to: d)
        #expect(c.droppedIndexes.isEmpty && c.createdIndexes.isEmpty)
        #expect(c.droppedForeignKeys.isEmpty && c.addedForeignKeys.isEmpty)
        #expect(c.alteredColumns.map(\.new.name) == ["mail", "team"])
        #expect(!c.primaryKeyChanged)
    }

    @Test func changedIndexIsDroppedAndCreated() {
        let s = users()
        var d = TableDesign(s)
        d.indexes[0].value.isUnique = true
        let c = StructureChange(from: s, to: d)
        #expect(c.droppedIndexes.map(\.name) == ["users_email_idx"])
        #expect(c.createdIndexes.map(\.name) == ["users_email_idx"])
    }

    @Test func droppedAndAddedColumns() {
        let s = users()
        var d = TableDesign(s)
        d.columns.removeAll { $0.value.name == "name" }
        d.columns.append(Designed(origin: nil, ColumnInfo(name: "bio", typeName: "text")))
        let c = StructureChange(from: s, to: d)
        #expect(c.droppedColumns.map(\.name) == ["name"])
        #expect(c.addedColumns.map(\.name) == ["bio"])
        #expect(c.alteredColumns.isEmpty)
    }
}

@Suite struct PostgresDDLTests {
    @Test func everyKindOfChange() throws {
        let s = users(schema: "app")
        var d = TableDesign(s)
        column(&d, "email") { $0.name = "mail"; $0.typeName = "text"; $0.comment = "login" }
        column(&d, "age") { $0.defaultExpression = nil; $0.isNullable = false }
        column(&d, "id") { $0.isAutoIncrement = true }
        d.columns.removeAll { $0.value.name == "name" }
        d.columns.append(Designed(origin: nil, ColumnInfo(name: "bio", typeName: "text", defaultExpression: "''", comment: "about")))
        d.indexes = [Designed(origin: nil, IndexInfo(name: "", columns: ["mail", "age"], isUnique: true))]
        d.foreignKeys = []
        d.primaryKey = ["id", "mail"]
        d.name = "people"
        let plan = try pg.alterTable(StructureChange(from: s, to: d))
        #expect(plan.isAtomic)
        #expect(plan.statements == [
            #"ALTER TABLE "app"."users" DROP CONSTRAINT "users_team_fk""#,
            #"ALTER TABLE "app"."users" DROP CONSTRAINT "users_pkey""#,
            #"DROP INDEX "app"."users_email_idx""#,
            #"ALTER TABLE "app"."users" DROP COLUMN "name""#,
            #"ALTER TABLE "app"."users" RENAME COLUMN "email" TO "mail""#,
            #"ALTER TABLE "app"."users" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY"#,
            #"ALTER TABLE "app"."users" ALTER COLUMN "mail" TYPE text"#,
            #"COMMENT ON COLUMN "app"."users"."mail" IS 'login'"#,
            #"ALTER TABLE "app"."users" ALTER COLUMN "age" DROP DEFAULT"#,
            #"ALTER TABLE "app"."users" ALTER COLUMN "age" SET NOT NULL"#,
            #"ALTER TABLE "app"."users" ADD COLUMN "bio" text DEFAULT ''"#,
            #"COMMENT ON COLUMN "app"."users"."bio" IS 'about'"#,
            #"ALTER TABLE "app"."users" ADD PRIMARY KEY ("id", "mail")"#,
            #"CREATE UNIQUE INDEX "users_mail_age_key" ON "app"."users" ("mail", "age")"#,
            #"ALTER TABLE "app"."users" RENAME TO "people""#,
        ])
    }

    @Test func uniqueConstraintIsDroppedAsAConstraint() throws {
        var s = users()
        s.indexes.append(IndexInfo(name: "users_name_key", columns: ["name"], isUnique: true, isConstraint: true))
        var d = TableDesign(s)
        d.indexes.removeAll { $0.value.name == "users_name_key" }
        #expect(try pg.alterTable(StructureChange(from: s, to: d)).statements == [
            #"ALTER TABLE "users" DROP CONSTRAINT "users_name_key""#,
        ])
    }

    @Test func createTable() {
        let d = TableDesign(
            name: "teams",
            columns: [
                Designed(origin: nil, ColumnInfo(name: "id", typeName: "bigint", isNullable: false, isAutoIncrement: true)),
                Designed(origin: nil, ColumnInfo(name: "name", typeName: "text", isNullable: false, comment: "shown")),
                Designed(origin: nil, ColumnInfo(name: "owner", typeName: "bigint")),
            ],
            primaryKey: ["id"],
            indexes: [Designed(origin: nil, IndexInfo(name: "", columns: ["name"]))],
            foreignKeys: [Designed(origin: nil, ForeignKeyInfo(name: "", columns: ["owner"], referencedTable: TableRef(schema: "app", "users"), referencedColumns: ["id"], onDelete: "SET NULL"))])
        #expect(pg.createTable(d, schema: "app").preview == """
            CREATE TABLE "app"."teams" (
              "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
              "name" text NOT NULL,
              "owner" bigint,
              PRIMARY KEY ("id"),
              FOREIGN KEY ("owner") REFERENCES "users" ("id") ON DELETE SET NULL
            );
            CREATE INDEX "teams_name_idx" ON "app"."teams" ("name");
            COMMENT ON COLUMN "app"."teams"."name" IS 'shown';
            """)
    }

    @Test func dropTruncateRename() throws {
        let t = DatabaseObject(TableRef(schema: "app", "users"), kind: .table)
        #expect(try pg.drop(t, options: DropOptions(cascade: true)).statements == [#"DROP TABLE "app"."users" CASCADE"#])
        #expect(pg.truncate(t.ref, options: TruncateOptions(restartIdentity: true, cascade: true), hasAutoIncrement: false).statements
            == [#"TRUNCATE TABLE "app"."users" RESTART IDENTITY CASCADE"#])
        #expect(try pg.rename(t, to: "people").statements == [#"ALTER TABLE "app"."users" RENAME TO "people""#])
        let v = DatabaseObject(TableRef("active"), kind: .materializedView)
        #expect(try pg.drop(v, options: DropOptions()).statements == [#"DROP MATERIALIZED VIEW "active""#])
    }
}

@Suite struct MySQLDDLTests {
    @Test func oneAlterKeepsWhatModifyWouldLose() throws {
        var s = users()
        s.columns[0].isAutoIncrement = true
        s.columns[1].collation = "utf8mb4_bin"
        s.columns.append(ColumnInfo(
            name: "updated", typeName: "timestamp", defaultExpression: "CURRENT_TIMESTAMP", onUpdate: "CURRENT_TIMESTAMP"))
        var d = TableDesign(s)
        column(&d, "email") { $0.typeName = "varchar(200)" }
        column(&d, "name") { $0.name = "full_name" }
        column(&d, "age") { $0.name = "years"; $0.comment = "it's an age" }
        column(&d, "updated") { $0.isNullable = false }
        d.columns.insert(Designed(origin: nil, ColumnInfo(name: "nick", typeName: "varchar(20)")), at: 2)
        d.foreignKeys[0].value.onDelete = "RESTRICT"
        d.indexes = []
        d.comment = "people"
        let plan = try my.alterTable(StructureChange(from: s, to: d))
        #expect(!plan.isAtomic)
        #expect(plan.statements == [
            "ALTER TABLE `users` DROP FOREIGN KEY `users_team_fk`",
            """
            ALTER TABLE `users`
              DROP INDEX `users_email_idx`,
              MODIFY COLUMN `email` varchar(200) COLLATE utf8mb4_bin NOT NULL,
              RENAME COLUMN `name` TO `full_name`,
              CHANGE COLUMN `age` `years` integer NULL DEFAULT 0 COMMENT 'it\\'s an age',
              MODIFY COLUMN `updated` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
              ADD COLUMN `nick` varchar(20) NULL AFTER `email`,
              ADD CONSTRAINT `users_team_fk` FOREIGN KEY (`team_id`) REFERENCES `teams` (`id`) ON DELETE RESTRICT,
              COMMENT = 'people'
            """,
        ])
    }

    @Test func primaryKeyAndIndexes() throws {
        let s = users()
        var d = TableDesign(s)
        d.primaryKey = ["id", "email"]
        d.indexes.append(Designed(origin: nil, IndexInfo(name: "ft", columns: ["name"], method: "FULLTEXT")))
        let plan = try my.alterTable(StructureChange(from: s, to: d))
        #expect(plan.isAtomic)
        #expect(plan.statements == ["""
            ALTER TABLE `users`
              DROP PRIMARY KEY,
              ADD PRIMARY KEY (`id`, `email`),
              ADD FULLTEXT INDEX `ft` (`name`)
            """])
    }

    @Test func dropAndTruncateCanSkipForeignKeyChecks() throws {
        let t = DatabaseObject(TableRef("users"), kind: .table)
        #expect(try my.drop(t, options: DropOptions(ignoreForeignKeys: true)).preview == """
            SET FOREIGN_KEY_CHECKS = 0;
            DROP TABLE `users`;
            SET FOREIGN_KEY_CHECKS = 1;
            """)
        #expect(my.truncate(t.ref, options: TruncateOptions(), hasAutoIncrement: true).statements == ["TRUNCATE TABLE `users`"])
        #expect(try my.rename(t, to: "people").statements == ["RENAME TABLE `users` TO `people`"])
    }
}

@Suite struct SQLiteDDLTests {
    static let definition = """
        CREATE TABLE users (
          id INTEGER PRIMARY KEY AUTOINCREMENT,
          email TEXT NOT NULL COLLATE NOCASE UNIQUE,
          name TEXT CHECK (length(name) < 50),
          age INTEGER DEFAULT 0 CONSTRAINT age_ok CHECK (age >= 0),
          team_id INTEGER REFERENCES teams (id) ON DELETE CASCADE,
          total INTEGER GENERATED ALWAYS AS (age * 2) VIRTUAL,
          CHECK (email <> name)
        ) STRICT
        """

    func structure() -> TableStructure {
        var s = users(definition: Self.definition)
        s.columns[0].isAutoIncrement = true
        s.columns.append(ColumnInfo(name: "total", typeName: "INTEGER", generated: "GENERATED ALWAYS AS (age * 2) VIRTUAL"))
        s.indexes.append(IndexInfo(name: "sqlite_autoindex_users_1", columns: ["email"], isUnique: true, isConstraint: true))
        s.triggers = [TriggerInfo(name: "t", timing: "AFTER", events: ["UPDATE"], definition: "CREATE TRIGGER t AFTER UPDATE OF email ON users BEGIN SELECT 1; END")]
        return s
    }

    @Test func parsesClauses() throws {
        let p = try #require(SQLiteTableSQL(Self.definition))
        #expect(p.columns.map(\.name) == ["id", "email", "name", "age", "team_id", "total"])
        #expect(p.columns[1].type == "TEXT")
        #expect(p.columns[1].clauses.map(\.kind) == [.notNull, .collate, .unique])
        #expect(p.columns[3].clauses.map(\.text) == ["DEFAULT 0", "CONSTRAINT age_ok CHECK (age >= 0)"])
        #expect(p.columns[4].clauses.first?.referencedTable == "teams")
        #expect(p.generatedClause("total") == "GENERATED ALWAYS AS (age * 2) VIRTUAL")
        #expect(p.isAutoIncrement("id"))
        #expect(p.constraints.map(\.kind) == [.check])
        #expect(p.options == "STRICT")
        #expect(SQLiteTableSQL("CREATE TABLE t AS SELECT 1") == nil)
    }

    @Test func renamesAndAddsInPlace() throws {
        let s = structure()
        var d = TableDesign(s)
        column(&d, "name") { $0.name = "full name" }
        d.columns.append(Designed(origin: nil, ColumnInfo(name: "bio", typeName: "TEXT", defaultExpression: "'none'")))
        d.indexes.append(Designed(origin: nil, IndexInfo(name: "users_age", columns: ["age"])))
        let plan = try sqlite.alterTable(StructureChange(from: s, to: d))
        #expect(plan.setup.isEmpty)
        #expect(plan.statements == [
            #"ALTER TABLE "users" RENAME COLUMN "name" TO "full name""#,
            #"ALTER TABLE "users" ADD COLUMN "bio" TEXT DEFAULT 'none'"#,
            #"CREATE INDEX "users_age" ON "users" ("age")"#,
        ])
    }

    @Test func droppingAnIndexedColumnDropsItsIndexFirst() throws {
        let s = structure()
        var d = TableDesign(s)
        d.columns.removeAll { $0.value.name == "age" }
        // `age` has a CHECK of its own, which SQLite's DROP COLUMN accepts; no table CHECK uses it.
        d.indexes = d.indexes.filter { !$0.value.columns.contains("age") }
        #expect(try sqlite.alterTable(StructureChange(from: s, to: d)).statements == [
            #"ALTER TABLE "users" DROP COLUMN "age""#,
        ])
    }

    @Test func rebuildKeepsWhatItDoesNotChange() throws {
        let s = structure()
        var d = TableDesign(s)
        column(&d, "name") { $0.isNullable = false; $0.name = "nm" }
        column(&d, "age") { $0.defaultExpression = "abs(-1)" }
        column(&d, "email") { $0.typeName = "VARCHAR(200)" }
        d.foreignKeys = []
        d.indexes[0].value.columns = ["email", "nm"]   // users_email_idx
        let plan = try sqlite.alterTable(StructureChange(from: s, to: d))
        #expect(plan.setup == ["PRAGMA legacy_alter_table = ON"])
        #expect(plan.teardown == ["PRAGMA legacy_alter_table = OFF"])
        #expect(plan.statements == [
            """
            CREATE TABLE "tabula_new_users" (
              "id" INTEGER PRIMARY KEY AUTOINCREMENT,
              "email" VARCHAR(200) NOT NULL COLLATE NOCASE UNIQUE,
              "nm" TEXT CHECK (length("nm") < 50) NOT NULL,
              "age" INTEGER CONSTRAINT age_ok CHECK (age >= 0) DEFAULT (abs(-1)),
              "team_id" INTEGER,
              "total" INTEGER GENERATED ALWAYS AS (age * 2) VIRTUAL,
              CHECK (email <> "nm")
            ) STRICT
            """,
            #"INSERT INTO "tabula_new_users" ("id", "email", "nm", "age", "team_id") SELECT "id", "email", "name", "age", "team_id" FROM "users""#,
            #"DROP TABLE "users""#,
            #"ALTER TABLE "tabula_new_users" RENAME TO "users""#,
            #"CREATE INDEX "users_email_idx" ON "users" ("email", "nm")"#,
            #"CREATE TRIGGER t AFTER UPDATE OF email ON users BEGIN SELECT 1; END"#,
        ])
    }

    @Test func rebuildWithNewPrimaryKeyAndEnforcedForeignKeys() throws {
        var s = users(definition: "CREATE TABLE users (id INTEGER, email TEXT NOT NULL, name TEXT, age INTEGER DEFAULT 0, team_id INTEGER, PRIMARY KEY (id), FOREIGN KEY (team_id) REFERENCES teams (id))")
        s.indexes.removeAll { $0.name == "users_email_idx" }
        s.foreignKeysEnforced = true
        var d = TableDesign(s)
        d.primaryKey = ["id", "email"]
        d.foreignKeys.append(Designed(origin: nil, ForeignKeyInfo(name: "", columns: ["name"], referencedTable: TableRef("names"), referencedColumns: ["n"])))
        let plan = try sqlite.alterTable(StructureChange(from: s, to: d))
        #expect(plan.setup == ["PRAGMA foreign_keys = OFF", "PRAGMA legacy_alter_table = ON"])
        #expect(plan.teardown == ["PRAGMA legacy_alter_table = OFF", "PRAGMA foreign_keys = ON"])
        #expect(plan.statements[0] == """
            CREATE TABLE "tabula_new_users" (
              "id" INTEGER,
              "email" TEXT NOT NULL,
              "name" TEXT,
              "age" INTEGER DEFAULT 0,
              "team_id" INTEGER,
              FOREIGN KEY (team_id) REFERENCES teams (id),
              PRIMARY KEY ("id", "email"),
              FOREIGN KEY ("name") REFERENCES "names" ("n")
            )
            """)
    }

    @Test func createTableWithAutoIncrementKey() {
        let d = TableDesign(
            name: "notes",
            columns: [
                Designed(origin: nil, ColumnInfo(name: "id", typeName: "INTEGER", isNullable: false, isAutoIncrement: true)),
                Designed(origin: nil, ColumnInfo(name: "body", typeName: "TEXT", defaultExpression: "CURRENT_TIMESTAMP")),
            ],
            primaryKey: ["id"])
        #expect(sqlite.createTable(d, schema: nil).statements == ["""
            CREATE TABLE "notes" (
              "id" INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,
              "body" TEXT DEFAULT CURRENT_TIMESTAMP
            )
            """])
    }

    @Test func truncateForgetsTheCounterOnlyWhenAsked() {
        let t = TableRef("users")
        #expect(sqlite.truncate(t, options: TruncateOptions(), hasAutoIncrement: true).statements == [#"DELETE FROM "users""#])
        #expect(sqlite.truncate(t, options: TruncateOptions(restartIdentity: true), hasAutoIncrement: true).statements
            == [#"DELETE FROM "users""#, #"DELETE FROM "sqlite_sequence" WHERE name = 'users'"#])
    }

    @Test func plainDefaults() {
        for e in ["0", "-1.5", "'x'", "'it''s'", "NULL", "true", "CURRENT_TIMESTAMP"] { #expect(isPlainDefault(e), "\(e)") }
        for e in ["now()", "'a' || 'b'", "1 + 1", ""] { #expect(!isPlainDefault(e), "\(e)") }
    }
}
